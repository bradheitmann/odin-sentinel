import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
import { describe, expect, it } from "vitest";
import { createServer } from "../../src/mcp/server.js";
import { validateCmuxDeliveryProof } from "../../src/protocol/index.js";

// SLICE say-validator-roundtrip. ODIN now has both halves of the delivery seam: the
// Rust sender (crates/odin-say) writes proof records, and the TypeScript validator
// (odin.validate_cmux_delivery_proof) judges them. Nothing proved they agree. This test
// consumes the sender's committed golden corpus (generated by its own Rust test from the
// real sender flow) and asserts three things per record: the validator verdict, the MCP
// tool's identical verdict, and one PlanGraph delivery-fact outcome.

type ProofRecord = {
  record_kind: "delivery" | "send_refusal";
  timestamp: string;
  subcommand: string;
  target_surface_locator: string;
  submitted: boolean;
  verification_method: string;
  observed_processing_state: string;
  sender_role: string;
  note: string;
  polls: number;
  waited_ms: number;
  harness: string;
  harness_source: string;
  queued: boolean;
};

const GOLDEN = fileURLToPath(
  new URL("../../crates/odin-say/tests/fixtures/records/golden.jsonl", import.meta.url)
);

const records: ProofRecord[] = readFileSync(GOLDEN, "utf8")
  .trim()
  .split("\n")
  .map((line) => JSON.parse(line) as ProofRecord);

/** One row per corpus record, in corpus order; the shape check below binds them. */
function shape(record: ProofRecord): string {
  return [record.record_kind, record.observed_processing_state, record.submitted, record.note, record.harness].join("|");
}

/** The corpus shapes, in order. Proves the tables below line up with the file. */
const CORPUS_SHAPES: string[] = [
  "delivery|DELIVERED_ACKED|true|echoed|codex",
  "delivery|DELIVERED_NO_ACK|true|processing|codex",
  "delivery|PANE_STILL_THINKING|true|queued|pi",
  "send_refusal|PANE_STILL_THINKING|false|pre-send|codex",
  "send_refusal|PANE_BLOCKED_ON_PERMISSION|false|pre-send|unknown",
  "delivery|INPUT_BAR_ONLY|true|queue-not-proven|pi",
  "send_refusal|INPUT_BAR_ONLY|false|stale-text-stuck|unknown",
  "send_refusal|INPUT_BAR_ONLY|false|send-failed|codex",
  "send_refusal|INPUT_BAR_ONLY|false|send-failed|pi",
  "delivery|INPUT_BAR_ONLY|true|after-2-enters|codex"
];

type Verdict = { valid: boolean; delivery: "delivered" | "delivered_no_ack" | "not_delivered" | "not_proven" };

const EXPECTED_VERDICTS: Verdict[] = [
  { valid: true, delivery: "delivered" },
  { valid: true, delivery: "delivered_no_ack" },
  { valid: true, delivery: "delivered_no_ack" },
  { valid: true, delivery: "not_delivered" },
  { valid: true, delivery: "not_delivered" },
  { valid: false, delivery: "not_proven" },
  { valid: true, delivery: "not_delivered" },
  { valid: true, delivery: "not_delivered" },
  { valid: true, delivery: "not_delivered" },
  { valid: false, delivery: "not_proven" }
];

// Mapping onto PlanGraph delivery facts (no PlanGraph code is imported). The vocabulary
// owner's ruling (PM-PLANGRAPH, spec state-machines.json `delivery`, S-DETAIL-053) is
// explicit: TRANSPORT_ACK / transport_accepted needs `submitted` AND evidence that the
// harness took the input in — the input bar cleared, processing started, or the harness
// showing it queued. INPUT_BAR_ONLY is evidence of the opposite, so it maps to NO fact
// whatever its record_kind, and so does a send_refusal.
//   DELIVERED_ACKED read-back                    -> recipient_observed
//   DELIVERED_NO_ACK with processing observed    -> transport_accepted
//   pi queued steer (harness shows it queued)     -> transport_accepted
//   send_refusal (busy, blocked)                  -> no_fact
//   any INPUT_BAR_ONLY record                     -> no_fact
type FactOutcome = "recipient_observed" | "transport_accepted" | "no_fact";

const PLANGRAPH_OUTCOMES: FactOutcome[] = [
  "recipient_observed",
  "transport_accepted",
  "transport_accepted",
  "no_fact",
  "no_fact",
  "no_fact",
  "no_fact",
  "no_fact",
  "no_fact",
  "no_fact"
];

function factFor(record: ProofRecord): FactOutcome {
  // Ruling: the bar still holding the text is evidence the harness did NOT take it in.
  if (record.observed_processing_state === "INPUT_BAR_ONLY") return "no_fact";
  if (record.record_kind === "send_refusal") return "no_fact";
  if (!record.submitted) return "no_fact";
  return record.observed_processing_state === "DELIVERED_ACKED" ? "recipient_observed" : "transport_accepted";
}

// Sender exit codes that can never appear in the corpus: no record is written for them.
const NO_RECORD_EXITS: ReadonlyArray<{ exit: number; reason: string }> = [
  { exit: 1, reason: "generic run error before any record could be written" },
  { exit: 8, reason: "proof-log preflight refuses before any pane contact" },
  { exit: 9, reason: "record lost after the send; the log is deliberately empty, JSON on stderr" }
];

function parseToolResult(result: Awaited<ReturnType<Client["callTool"]>>): Record<string, unknown> {
  const content = result.content as Array<{ type: string; text?: string }>;
  const first = content[0];
  if (!first || first.type !== "text") throw new Error("Expected text tool result");
  return JSON.parse(first.text ?? "") as Record<string, unknown>;
}

describe("odin-say records and ODIN's validator agree", () => {
  it("the golden corpus covers every recordable sender exit exactly once", () => {
    expect(records.length).toBe(CORPUS_SHAPES.length);
    expect(EXPECTED_VERDICTS.length).toBe(records.length);
    expect(PLANGRAPH_OUTCOMES.length).toBe(records.length);
    expect(records.map(shape)).toEqual(CORPUS_SHAPES);
    // Every record carries the delivery-proof fields with the right types.
    for (const record of records) {
      expect(record.verification_method).toBe("read_screen");
      expect(record.target_surface_locator).toBe("surface:7");
      expect(typeof record.timestamp).toBe("string");
      expect(typeof record.queued).toBe("boolean");
      expect(typeof record.harness).toBe("string");
      expect(record.harness_source.length).toBeGreaterThan(0);
    }
    // Exit coverage: every exit that writes a record appears; the rest are named below.
    expect(records.map((record) => record.note).sort()).toEqual(
      [
        "after-2-enters",
        "echoed",
        "pre-send",
        "pre-send",
        "processing",
        "queue-not-proven",
        "queued",
        "send-failed",
        "send-failed",
        "stale-text-stuck"
      ].sort()
    );
    // Exits 4 (stale-text-stuck), 5 (send-failed, both call sites) and 6 (after-2-enters)
    // are the ones the first corpus missed; exits 1, 8 and 9 cannot be corpus-able.
    expect(records.filter((record) => record.note === "send-failed")).toHaveLength(2);
    expect(NO_RECORD_EXITS.map((entry) => entry.exit)).toEqual([1, 8, 9]);
    for (const entry of NO_RECORD_EXITS) {
      expect(entry.reason.length).toBeGreaterThan(10);
    }
  });

  it("validateCmuxDeliveryProof returns the expected valid/delivery for every record", () => {
    records.forEach((record, index) => {
      const expected = EXPECTED_VERDICTS[index];
      const result = validateCmuxDeliveryProof({ ...record });
      expect({ valid: result.valid, delivery: result.delivery }, shape(record)).toEqual(expected);
    });
    // Every refusal is a VALID record that is NOT a delivery.
    for (const refusal of records.filter((record) => record.record_kind === "send_refusal")) {
      const result = validateCmuxDeliveryProof({ ...refusal });
      expect(result.valid, shape(refusal)).toBe(true);
      expect(result.delivery, shape(refusal)).toBe("not_delivered");
    }
  });

  it("the MCP tool returns the same verdict for every record", async () => {
    const server = createServer();
    const client = new Client({ name: "say-validator-roundtrip", version: "1.0.0" });
    const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
    await server.connect(serverTransport);
    await client.connect(clientTransport);
    try {
      for (const [index, record] of records.entries()) {
        const expected = EXPECTED_VERDICTS[index];
        const fromTool = parseToolResult(
          await client.callTool({
            name: "odin.validate_cmux_delivery_proof",
            arguments: { proof: { ...record } }
          })
        );
        expect({ valid: fromTool.valid, delivery: fromTool.delivery }, shape(record)).toEqual(expected);
        // The MCP boundary carries exactly what the library said.
        const direct = validateCmuxDeliveryProof({ ...record });
        expect(fromTool.delivery, shape(record)).toBe(direct.delivery);
        expect(fromTool.valid, shape(record)).toBe(direct.valid);
      }
    } finally {
      await client.close();
      await server.close();
    }
  });

  it("the PlanGraph mapping is total and follows the record fields", () => {
    const mapped = new Set<FactOutcome>();
    records.forEach((record, index) => {
      expect(PLANGRAPH_OUTCOMES[index], shape(record)).toBe(factFor(record));
      mapped.add(PLANGRAPH_OUTCOMES[index]);
    });
    // Totality: one row per corpus record, and every outcome class is exercised.
    expect(PLANGRAPH_OUTCOMES.length).toBe(records.length);
    expect([...mapped].sort()).toEqual(["no_fact", "recipient_observed", "transport_accepted"]);
    // The ruling: every INPUT_BAR_ONLY record maps to NO fact, whatever its record_kind...
    for (const record of records.filter((record) => record.observed_processing_state === "INPUT_BAR_ONLY")) {
      expect(PLANGRAPH_OUTCOMES[records.indexOf(record)], shape(record)).toBe("no_fact");
    }
    // ...refusals never produce a delivery fact...
    for (const refusal of records.filter((record) => record.record_kind === "send_refusal")) {
      expect(PLANGRAPH_OUTCOMES[records.indexOf(refusal)], shape(refusal)).toBe("no_fact");
    }
    // ...and a submitted send that is neither acknowledged nor stuck in the bar is
    // transport_accepted (never recipient_observed).
    for (const record of records.filter(
      (candidate) =>
        candidate.submitted &&
        candidate.observed_processing_state !== "DELIVERED_ACKED" &&
        candidate.observed_processing_state !== "INPUT_BAR_ONLY"
    )) {
      expect(PLANGRAPH_OUTCOMES[records.indexOf(record)], shape(record)).toBe("transport_accepted");
    }
  });
});
